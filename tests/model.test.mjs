import assert from 'node:assert/strict';
import {freshTree,freshNode,projectTree,purchase,validateTree,rankOf,canBuy} from '../scripts/model.mjs';
const t=freshTree('Private Path');
const alice='a',bob='b';
t.users=[alice];
const root=freshNode('First Spark',0,0), advanced=freshNode('Hidden Reward',-140,220);
advanced.requires=[root.id];
t.nodes=[root,advanced];
root.notes='GM-ONLY PRIVATE TALENT NOTES';
t.shared.points=4;
assert.equal(projectTree(t,bob),null,'unauthorized player must have NO tree');
assert.deepEqual(projectTree(t,alice).nodes.map(n=>n.name),['First Spark'],'frontier does not leak future node');
assert.ok(!JSON.stringify(projectTree(t,alice)).includes('Hidden Reward'),'secret node must not appear in payload');
assert.ok(!JSON.stringify(projectTree(t,alice)).includes('GM-ONLY PRIVATE TALENT NOTES'),'private editor notes must not appear in projection');
assert.equal(canBuy(t,root,t.shared),true);
assert.equal(canBuy(t,advanced,t.shared),false);
purchase(t,root.id,alice);
assert.equal(rankOf(t.shared,root.id),1);
assert.equal(t.shared.points,3);
assert.deepEqual(projectTree(t,alice).nodes.map(n=>n.name),['First Spark','Hidden Reward']);
assert.throws(()=>purchase(t,advanced.id,bob),/not assigned/);
t.visibility='discovered';assert.deepEqual(projectTree(t,alice).nodes.map(n=>n.name),['First Spark']);
t.visibility='full';assert.equal(projectTree(t,alice).nodes.length,2);
t.progression='personal';t.personal={};assert.equal(projectTree(t,alice).progress.points,0);
t.personal[alice]={points:3,ranks:{}};t.personal[bob]={points:4,ranks:{}};
purchase(t,root.id,alice);assert.equal(rankOf(t.personal[alice],root.id),1);assert.equal(rankOf(t.personal[bob],root.id),0);
// GM can spend despite not being assigned.
t.access='gm';assert.throws(()=>purchase(t,root.id,alice),/not assigned/);
t.personal.gm={points:2,ranks:{}};
purchase(t,root.id,'gm',true);
assert.equal(validateTree(t),true);
advanced.requires=[root.id];root.requires=[advanced.id];assert.throws(()=>validateTree(t),/Circular/);
console.log('Brazier model tests: PASSED');
